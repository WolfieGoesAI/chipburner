#!/usr/bin/env python3
# Generates Sources/DisasmTables.swift from MAME's disassembler sources (BSD-3-Clause):
#   z80/z80dasm.{h,cpp} (Juergen Buchmueller), upd7810/upd7810_dasm.{h,cpp} (Juergen Buchmueller),
#   m6809/6x09dasm.cpp (Nathan Woods, Sean Riddle, Tim Lindner), m6502/dm6502.lst (Olivier Galibert),
#   mcs51/mcs51dasm.cpp (Steve Ellenoff).
# Usage: gen_disasm_tables.py <mame>/src/devices/cpu > Sources/DisasmTables.swift
import re, sys

cpu = sys.argv[1]
def read(p): return open(f"{cpu}/{p}", encoding="utf-8").read()
def strip_comments(s): return re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", s), flags=re.S)
def sw(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
def block(src, header):
    i = src.index(header); j = src.index("{", i); depth = 0
    for k in range(j, len(src)):
        if src[k] == "{": depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0: return src[j + 1:k]
    raise ValueError(header)
def entries(body):
    out, depth, cur = [], 0, None
    for ch in body:
        if ch == "{":
            depth += 1
            if depth == 1: cur = ""; continue
        elif ch == "}":
            depth -= 1
            if depth == 0: out.append(cur.strip()); cur = None; continue
        if depth >= 1: cur += ch
    return out
out = ["// Generated by scripts/gen_disasm_tables.py from MAME's disassemblers (BSD-3-Clause). Don't edit.",
       "// z80dasm & upd7810_dasm © Juergen Buchmueller; 6x09dasm © Nathan Woods, Sean Riddle, Tim Lindner;",
       "// m6502 tables © Olivier Galibert; mcs51dasm © Steve Ellenoff.", "", "enum DisasmTables {"]

# ---- Z80
zh = strip_comments(read("z80/z80dasm.h")); zc = strip_comments(read("z80/z80dasm.cpp"))
enum = re.findall(r"\b(z[A-Z0-9]+)\b", block(zh, "enum e_mnemonics"))
mn = re.findall(r'"([^"]*)"', block(zc, "s_mnemonic[] ="))
assert len(enum) == len(mn), (len(enum), len(mn))
idx = {n: i for i, n in enumerate(enum)}
out.append("    static let z80Mnemonics: [String] = [" + ", ".join(sw(m) for m in mn) + "]")
for name in ["mnemonic_main", "mnemonic_cb", "mnemonic_ed", "mnemonic_xx", "mnemonic_xx_cb"]:
    es = entries(block(zc, f"z80_disassembler::{name}[256] ="))
    assert len(es) == 256, (name, len(es))
    ms, args = [], []
    for e in es:
        m = re.fullmatch(r'(z[A-Z0-9]+)\s*,\s*(nullptr|"([^"]*)")', e)
        assert m, e
        ms.append(str(idx[m.group(1)]))
        a = m.group(3)
        assert a != "", e
        args.append(sw(a) if a is not None else "nil")
    swname = "z80" + "".join(p.capitalize() for p in name.split("_")[1:])
    out.append(f"    static let {swname}M: [UInt8] = [" + ",".join(ms) + "]")
    out.append(f"    static let {swname}A: [String?] = [" + ", ".join(args) + "]")

# ---- uPD7810
uh = strip_comments(read("upd7810/upd7810_dasm.h")); uc = strip_comments(read("upd7810/upd7810_dasm.cpp"))
tokens = [t for t in re.findall(r"\b([A-Za-z_][A-Za-z0-9_]*)\b", block(uh, "enum\n"))]
names = re.findall(r'"([^"]*)"', block(uc, "dasm_s::token_names[] ="))
assert len(tokens) == len(names), (len(tokens), len(names))
tix = {t: i for i, t in enumerate(tokens)}
out.append("    static let upd7810Tokens: [String] = [" + ", ".join(sw(n) for n in names) + "]")
for t in ["d60", "d70", "d74", "d48_7810", "d4C_7810", "d4D_7810", "d64_7810", "XX_7810"]:
    hdr = re.search(r"::" + t + r"\[256\] =", uc).group(0)
    es = entries(block(uc, hdr))
    assert len(es) == 256, (t, len(es))
    enc = []
    for e in es:
        if e == "": enc.append(sw(f"{tix['illegal']}"))
        elif re.fullmatch(r"d\w+", e): enc.append(sw("@" + e))
        else:
            m = re.fullmatch(r'(\w+)\s*,\s*(nullptr|"([^"]*)")\s*,?', e)
            assert m, e
            enc.append(sw(f"{tix[m.group(1)]}" + ("" if m.group(3) is None else "|" + m.group(3))))
    out.append(f"    static let upd7810_{t}: [String] = [" + ", ".join(enc) + "]")

# ---- 6502
lst = [l for l in read("m6502/dm6502.lst").splitlines() if l and not l.startswith("#") and l != "reset"]
ops = " ".join(lst).split()
assert len(ops) == 256, len(ops)
out.append("    static let m6502: [String] = [" + ", ".join(sw(o) for o in ops) + "]")

# ---- 6809 (M6x09_GENERAL | M6809_UNDOCUMENTED, first entry per opcode wins like std::set)
mc = strip_comments(read("m6809/6x09dasm.cpp"))
body = block(mc, "m6x09_disassembler::m6x09_opcodes[] =")
seen, rows = set(), []
for e in entries(body):
    parts = [p.strip() for p in e.split(",")]
    op, ln, name, mode, level = int(parts[0], 16), int(parts[1]), parts[2].strip('"'), parts[3], parts[4]
    flags = parts[5] if len(parts) > 5 else "0"
    lv = 0
    for l in level.split("|"):
        lv |= {"M6x09_GENERAL": 1, "M6809_UNDOCUMENTED": 2, "HD6309_EXCLUSIVE": 4}[l.strip()]
    if not (lv & 3) or op in seen: continue
    seen.add(op)
    fl = 0
    for f in flags.split("|"):
        f = f.strip()
        fl |= {"0": 0, "STEP_OVER": 1, "STEP_OUT": 2, "STEP_COND": 4}.get(f, 0)
    rows.append(f"        Op6809(op: 0x{op:04X}, len: {ln}, name: {sw(name)}, mode: .{mode})")
out.append("    struct Op6809 { let op: UInt16; let len: Int; let name: String; let mode: Mode6809 }")
out.append("    enum Mode6809 { case INH, PSHS, PSHU, PULS, PULU, DIR, DIR_IM, IND, REL, LREL, EXT, IMM, IMM_RR, IMM_BW, IMM_TFM, PG2, PG3 }")
out.append("    static let m6809: [Op6809] = [\n" + ",\n".join(rows) + "\n    ]")

# ---- 8051 default SFR / bit names
sc = strip_comments(read("mcs51/mcs51dasm.cpp"))
pairs = re.findall(r'\{\s*(0x[0-9a-fA-F]+)\s*,\s*"([^"]*)"\s*\}', block(sc, "mcs51_disassembler::default_names[] ="))
out.append("    static let mcs51Names: [Int: String] = [" + ", ".join(f"{a}: {sw(n)}" for a, n in pairs) + "]")
out.append("}")
print("\n".join(out))
